-- BRONZE load: runs as <ENV>_LOADER from the ADF pipeline (Script activity), one statement per block.
-- Bronze = data exactly as landed: one VARIANT per record + file lineage. Append-only across days.
--
-- {{DATE_PATH}} is replaced at run time with the pipeline's yyyy/MM/dd.
-- Idempotency: each run REPLACES that day's partition (DELETE by _SOURCE_FILE, then COPY ... FORCE = TRUE).
--   COPY's own load history is not enough: ADF re-runs rewrite the files, and Snowflake treats a
--   rewritten file (new ETag) as new, which double-loads it.
-- PATTERN is required: on ADLS Gen2 (hierarchical namespace) every folder is also listed as a 0-byte
--   object, which COPY would otherwise try (and fail) to parse.
CREATE FILE FORMAT IF NOT EXISTS BRONZE.FF_JSON TYPE = JSON;
CREATE FILE FORMAT IF NOT EXISTS BRONZE.FF_PARQUET TYPE = PARQUET;

CREATE TABLE IF NOT EXISTS BRONZE.RAW_TRIP_EVENTS (
  RECORD VARIANT, _SOURCE_FILE STRING, _FILE_ROW NUMBER, _FILE_LAST_MODIFIED TIMESTAMP_NTZ,
  _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
DELETE FROM BRONZE.RAW_TRIP_EVENTS WHERE _SOURCE_FILE LIKE 'raw/trip_events/{{DATE_PATH}}/%';
COPY INTO BRONZE.RAW_TRIP_EVENTS (RECORD, _SOURCE_FILE, _FILE_ROW, _FILE_LAST_MODIFIED)
  FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$FILE_LAST_MODIFIED
        FROM @BRONZE.ADLS_STAGE/raw/trip_events/{{DATE_PATH}}/)
  PATTERN = '.*[.]json'
  FILE_FORMAT = (FORMAT_NAME = 'BRONZE.FF_JSON') ON_ERROR = CONTINUE
  FORCE = TRUE;

