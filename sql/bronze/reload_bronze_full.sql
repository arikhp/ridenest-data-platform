-- BRONZE full reload: run by PL_BACKFILL (Script activity) as <ENV>_LOADER.
-- Rebuilds every bronze table from everything under bronze/raw/<source>/ (initial_load + daily folders).
-- PATTERN skips the 0-byte folder objects that ADLS Gen2 exposes; it also accepts *.csv because an ADF
-- CSV->Parquet copy with PreserveHierarchy keeps the source file name (content is Parquet).
CREATE FILE FORMAT IF NOT EXISTS BRONZE.FF_JSON TYPE = JSON;
CREATE FILE FORMAT IF NOT EXISTS BRONZE.FF_PARQUET TYPE = PARQUET;

CREATE TABLE IF NOT EXISTS BRONZE.RAW_TRIP_EVENTS (
  RECORD VARIANT, _SOURCE_FILE STRING, _FILE_ROW NUMBER, _FILE_LAST_MODIFIED TIMESTAMP_NTZ,
  _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
TRUNCATE TABLE BRONZE.RAW_TRIP_EVENTS;
COPY INTO BRONZE.RAW_TRIP_EVENTS (RECORD, _SOURCE_FILE, _FILE_ROW, _FILE_LAST_MODIFIED)
  FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, METADATA$FILE_LAST_MODIFIED
        FROM @BRONZE.ADLS_STAGE/raw/trip_events/)
  PATTERN = '.*[.]json'
  FILE_FORMAT = (FORMAT_NAME = 'BRONZE.FF_JSON') ON_ERROR = CONTINUE
  FORCE = TRUE;

